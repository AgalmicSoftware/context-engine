  startCacheWatch: () => void = () => {
    this.clearCacheWatch();

    const cacheTarget = this.resolveManagedCacheSeedTargets();
    const { primarySlug, primaryNetId } = cacheTarget;
    const netId = primaryNetId || null;
    if (!netId) return;
    const workerCacheIdentity = this.resolveManagedWorkerCacheIdentity(cacheTarget);
    if (netId === 'worker' && !workerCacheIdentity) return;
    const slug = canonicalizeLegacySessionAlias(primarySlug || '');

    const surveyIdLower = String(this.state.lastSubmittedSurveyId || '').toLowerCase();
    const questionIdsLower = (this.state.uploadedQuestions || [])
      .map((u: CreateQuestionsAndSurveysUploadedQuestion) => String(u.questionId || '').toLowerCase())
      .filter(Boolean);
    if (!surveyIdLower && questionIdsLower.length === 0) return;

    const watchedNamespace = this.state.surveyAddedSuccessfully
      ? 'surveysCache'
      : this.state.questionsAddedSuccessfully
        ? 'questionsCache'
        : null;
    let pollAttempts = 0;
    this._cacheWatchCheckNow = ({ countPollAttempt = false } = {}) => {
      if (countPollAttempt) {
        pollAttempts += 1;
      }
      let loaded = false;
      try {
        const currentIdentity = workerCacheIdentity ? this.resolveManagedWorkerCacheIdentity(cacheTarget) : null;
        const workerIdentityStillMatches =
          !workerCacheIdentity ||
          (!!currentIdentity &&
            currentIdentity.key === workerCacheIdentity.key &&
            workerCanonicalCacheIdentityMatches(
              readManagedCacheSnapshot(watchedNamespace || '', slug)?.[netId],
              workerCacheIdentity,
            ));
        if (workerIdentityStillMatches) {
          loaded = hasSubmittedResourcesInManagedCache({
            slug,
            netId,
            surveyAddedSuccessfully: this.state.surveyAddedSuccessfully,
            questionsAddedSuccessfully: this.state.questionsAddedSuccessfully,
            surveyId: surveyIdLower,
            questionIds: questionIdsLower,
          });
        }
      } catch {
        loaded = false;
      }

      if (loaded) {
        this.clearCacheWatch();
        if (this._isMounted) {
          this.setState(buildCreateSurveyCacheLoadedPatch());
        }
        return true;
      }

      if (countPollAttempt && pollAttempts > 60) {
        this.clearCacheWatch();
      }
      return false;
    };

    this._cacheWatchCoalescer = createCacheUpdateCoalescer(() => {
      if (typeof this._cacheWatchCheckNow === 'function') {
        this._cacheWatchCheckNow({ countPollAttempt: false });
      }
    });

    if (watchedNamespace) {
      this._cacheWatchUnsubscribe = subscribeCacheUpdates((event: CacheWatchUpdateEvent) => {
        if (!event || event.namespace !== watchedNamespace) return;
        if (String(event.slug || '') !== String(slug || '')) return;
        if (this._cacheWatchCoalescer) {
          this._cacheWatchCoalescer.schedule();
        }
      });
    }

    this._cacheWatchTimer = setInterval(() => {
      if (typeof this._cacheWatchCheckNow === 'function') {
        this._cacheWatchCheckNow({ countPollAttempt: true });
      }
    }, 1000);

    this._cacheWatchCheckNow({ countPollAttempt: true });
  };

